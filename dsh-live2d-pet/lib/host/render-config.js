/**
 * 渲染配置的取值边界 —— `maxFps` 的**唯一定义处**。
 *
 * ⚠️ 硬约束：**零 import、不碰任何 `node:` 内置模块**。
 *
 * 理由与 `actions.js` / `capabilities.js` 完全相同：客户端 bundle 会**内联**这个文件，
 * 一旦有人在这里写 `import fs from 'node:fs'`，esbuild 会当场构建失败。这是刻意选的
 * 失败方式 —— 构建时炸掉，而不是运行时让桌宠消失（方案文档 §9.2 那次白屏事故）。
 *
 * ── 为什么它需要一个自己的文件 ──────────────────────────────────────────
 *
 * `maxFps` 有两个使用者，而且分居两侧：
 *   1. `lib/index.js`（Host）—— 读插件配置，把**归一化之后**的值报进 `/status`；
 *   2. `src/client/frame-budget.ts`（渲染端）—— 拿它决定「这一帧画不画」。
 *
 * 两侧各写一份边界，症状是「配置里写 `maxFps: 0`，Host 如实报 0，渲染端算出
 * `1000 / 0 = Infinity` 的帧间隔 —— 于是桌宠**永久静止**，而两边都不报错」。
 * 与第八个缺陷（`MAX_TEXT_CHARS` 写了两遍）是同一个病：同一个数字，
 * 两个各自自洽的定义处。所以数字与夹取都只有这一份，由需要的人 import。
 *
 * ── 这个键曾经完全是装饰品 ──────────────────────────────────────────────
 *
 * 从 P0 起 `maxFps` 就被写进 `lib/index.js` 的配置说明、被读进 `/status`、
 * 在方案 §4.4 的 Config Schema 里写作 `render.maxFps`，而**从来没有任何代码
 * 用它做过任何事** —— 渲染循环无条件跟着显示器刷新率跑。用户把它设成 30
 * 想省电，风扇照转、面板上的帧率数字照旧，且不报任何错。第十个缺陷。
 */

/**
 * 允许的最低帧率上限。
 *
 * 再低就不是桌宠了 —— 4fps 的呼吸与眨眼看起来像卡死，而用户会去查
 * 「是不是模型坏了」。宁可拒绝一个荒唐的值，也不要交付一个看起来坏掉的功能。
 */
export const MIN_FPS = 10;

/**
 * 允许的最高帧率上限。
 *
 * 240 覆盖 240Hz 显示器（再往上的屏极少）。设更大不是「更快」而是**没有意义**：
 * 渲染循环由 rAF 驱动，rAF 由显示器刷新率驱动，所以超过刷新率的部分本来就拿不到；
 * 一个永远不生效的上限比一个被夹取过的上限更难查。
 */
export const MAX_FPS = 240;

/** 不配 `maxFps` 时用的默认值，与 `lib/index.js` 顶部那段配置说明一致。 */
export const DEFAULT_FPS = 60;

/**
 * 把任意输入夹成合法的帧率上限。
 *
 * 非数字 / 非有限数（`NaN`、`Infinity`、`'30'`、`null`、`undefined`）一律回默认值：
 * **不猜、也不 `Number()` 强转**。这个值最终决定「桌宠还动不动」，而猜错的
 * 方向是永久静止 —— 那比「配置没生效」严重得多。`'30'` 落回 60 而不是 30，
 * 是刻意选择：字符串说明配置写错了，那就该按「没配」处理。
 *
 * 夹取而不是拒绝：这是一个**性能档位**，用户写 `maxFps: 5` 的意图
 * （「我要它尽量省电」）是明确的，给 10 比给报错更有用。
 */
export function normalizeFps(value) {
  if (typeof value !== 'number' || !Number.isFinite(value)) return DEFAULT_FPS;
  if (value < MIN_FPS) return MIN_FPS;
  if (value > MAX_FPS) return MAX_FPS;
  return value;
}
